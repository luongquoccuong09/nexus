<#
.SYNOPSIS
    Regenerates docs/facts/INDEX.md and docs/decisions/INDEX.md from the frontmatter
    of the cards beside them, and fails when a card breaks the card contract.

.DESCRIPTION
    A fact card is docs/facts/<area>/<slug>.md; a decision record is
    docs/decisions/<yyyy-MM-dd>-<slug>.md. Both start with a YAML frontmatter block.
    Contracts are documented in docs/facts/README.md and docs/decisions/README.md.

    This script is ASCII-only so Windows PowerShell 5.1 and pwsh 7+ parse it identically.

.PARAMETER Check
    Do not write. Exit 1 when an index on disk differs from what would be generated.
#>
[CmdletBinding()]
param(
    [string]$Root,
    [switch]$Check
)

$ErrorActionPreference = 'Stop'
if (-not $Root) {
    $Root = (Resolve-Path (Join-Path (Split-Path -Parent $MyInvocation.MyCommand.Path) '..\..')).Path
}
$utf8 = New-Object System.Text.UTF8Encoding($false)
$problems = New-Object System.Collections.Generic.List[string]

function Read-Card([System.IO.FileInfo]$File, [string[]]$Required) {
    $text = [System.IO.File]::ReadAllText($File.FullName, $utf8) -replace "`r`n", "`n"
    $card = @{ File = $File }
    if ($text -notmatch '(?s)\A---\n(.*?)\n---\n') {
        $problems.Add("$($File.FullName): no frontmatter")
        return $card
    }
    foreach ($line in $Matches[1] -split "`n") {
        if ($line -match '^([A-Za-z-]+):\s*(.*)$') {
            $value = $Matches[2].Trim()
            if ($value.Length -ge 2 -and $value.StartsWith('"') -and $value.EndsWith('"')) {
                $value = $value.Substring(1, $value.Length - 2).Replace('\"', '"').Replace('\\', '\')
            }
            $card[$Matches[1]] = $value
        }
    }
    foreach ($key in $Required) {
        if (-not $card[$key]) { $problems.Add("$($File.FullName): frontmatter lacks '$key'") }
    }
    return $card
}

function Cell([string]$Text) { return ($Text -replace '\|', '\|') }

function Publish([string]$Path, [string[]]$Lines) {
    $new = ($Lines -join "`n") + "`n"
    $old = if (Test-Path $Path) { [System.IO.File]::ReadAllText($Path, $utf8) -replace "`r`n", "`n" } else { '' }
    if ($new -eq $old) { return }
    if ($Check) { $problems.Add("$Path is out of date; run scripts/audit/Build-KnowledgeIndex.ps1") }
    else { [System.IO.File]::WriteAllText($Path, $new, $utf8); Write-Host "wrote $Path" }
}

# ---- facts -----------------------------------------------------------------
$factsDir = Join-Path $Root 'docs\facts'
$validFactStatuses = @('verified', 'imported', 'superseded')
$lines = @(
    '# Facts Index',
    '',
    '<!-- Generated by scripts/audit/Build-KnowledgeIndex.ps1. Do not edit by hand. -->',
    ''
)
$total = 0
foreach ($area in Get-ChildItem $factsDir -Directory | Sort-Object Name) {
    $cards = @(Get-ChildItem $area.FullName -Filter *.md | Sort-Object Name |
        ForEach-Object { Read-Card $_ @('title', 'summary', 'area', 'recorded', 'status') })
    foreach ($card in $cards) {
        if ($card.area -and $card.area -ne $area.Name) {
            $problems.Add("$($card.File.FullName): area '$($card.area)' does not match folder '$($area.Name)'")
        }
        if ($card.status -and ($validFactStatuses -notcontains $card.status)) {
            $problems.Add("$($card.File.FullName): invalid fact status '$($card.status)'")
        }
    }
    $total += $cards.Count
    $lines += "## $($area.Name) ($($cards.Count))"
    $lines += ''
    if ($cards.Count -eq 0) {
        $lines += '_No cards recorded yet._'
        $lines += ''
        continue
    }
    $lines += '| Fact | Summary | Recorded | Status |'
    $lines += '|---|---|---|---|'
    foreach ($card in $cards) {
        $lines += "| [$(Cell $card.title)]($($area.Name)/$($card.File.Name)) | $(Cell $card.summary) | $($card.recorded) | $($card.status) |"
    }
    $lines += ''
}
$lines = @($lines[0], '', "$total cards.") + $lines[1..($lines.Count - 1)]
Publish (Join-Path $factsDir 'INDEX.md') $lines

# ---- decisions -------------------------------------------------------------
$decisionsDir = Join-Path $Root 'docs\decisions'
$validDecisionStatuses = @('accepted', 'open', 'relaxed', 'superseded')
$records = @(Get-ChildItem $decisionsDir -Filter *.md |
    Where-Object { $_.Name -notin @('README.md', 'INDEX.md') } | Sort-Object Name -Descending |
    ForEach-Object { Read-Card $_ @('id', 'title', 'summary', 'date', 'decided-by', 'status') })
$lines = @(
    '# Decisions Index',
    '',
    "$($records.Count) records, newest first.",
    '',
    '<!-- Generated by scripts/audit/Build-KnowledgeIndex.ps1. Do not edit by hand. -->',
    '',
    '| ID | Date | Decision | Summary | Status |',
    '|---|---|---|---|---|'
)
foreach ($record in $records) {
    if ($record.File.Name -notmatch '^\d{4}-\d{2}-\d{2}-') {
        $problems.Add("$($record.File.FullName): file name must start with yyyy-MM-dd-")
    }
    if ($record.status -and ($validDecisionStatuses -notcontains $record.status)) {
        $problems.Add("$($record.File.FullName): invalid decision status '$($record.status)'")
    }
    $lines += "| $(Cell $record.id) | $($record.date) | [$(Cell $record.title)]($($record.File.Name)) | $(Cell $record.summary) | $($record.status) |"
}
Publish (Join-Path $decisionsDir 'INDEX.md') $lines

if ($problems.Count -gt 0) {
    $problems | ForEach-Object { Write-Host "ERROR $_" -ForegroundColor Red }
    exit 1
}
Write-Host "Knowledge index OK: $total facts, $($records.Count) decisions."
