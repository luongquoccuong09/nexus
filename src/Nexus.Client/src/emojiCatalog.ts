const MODIFIER_BY_ID: Record<SkinToneId, string> = {
  default: '',
  light: '\u{1F3FB}',
  'medium-light': '\u{1F3FC}',
  medium: '\u{1F3FD}',
  'medium-dark': '\u{1F3FE}',
  dark: '\u{1F3FF}'
};

/**
 * Applies a Fitzpatrick skin-tone modifier to a tone-capable emoji,
 * properly handling variation selector-16 (U+FE0F) and ZWJ sequences.
 */
export function applySkinTone(emoji: string, tone: SkinToneId, toneCapable: boolean): string {
  const modifier = MODIFIER_BY_ID[tone];
  if (!toneCapable || !modifier) {
    return emoji;
  }
  const codePoints = Array.from(emoji);
  if (codePoints.length === 0) return emoji;
  const rest = codePoints[1] === '\uFE0F' ? codePoints.slice(2) : codePoints.slice(1);
  return [codePoints[0], modifier, ...rest].join('');
}

export function searchEmojis(query: string, entries: readonly EmojiEntry[] = EMOJI_CATALOG): EmojiEntry[] {
  const terms = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
  if (terms.length === 0) return [...entries];
  return entries.filter(entry => {
    const haystack = `${entry.name} ${entry.keywords} ${entry.emoji}`.toLowerCase();
    return terms.every(term => haystack.includes(term));
  });
}
